"use client";

import React, { useState } from "react";
import jsPDF from "jspdf";
import autoTable from "jspdf-autotable";
import { X, FileText, CheckCircle2 } from "lucide-react";

interface SyllabusPdfGeneratorModalProps {
  open: boolean;
  onClose: () => void;
  subjectName: string;
}

interface ParsedUnit {
  title: string;
  topics: string;
}

export default function SyllabusPdfGeneratorModal({
  open,
  onClose,
  subjectName,
}: SyllabusPdfGeneratorModalProps) {
  const [text, setText] = useState("");
  const [parsedUnits, setParsedUnits] = useState<ParsedUnit[]>([]);
  const [error, setError] = useState("");
  const [localSubjectName, setLocalSubjectName] = React.useState(subjectName || "");

  React.useEffect(() => {
    if (open) {
      setLocalSubjectName(subjectName || "");
    }
  }, [open, subjectName]);

  if (!open) return null;

  const handleParse = () => {
    setError("");
    if (!text.trim()) {
      setError("Please paste some syllabus text first.");
      return;
    }

    const lines = text.split("\n");
    const units: ParsedUnit[] = [];
    let currentUnit: ParsedUnit | null = null;

    // Regex to match "UNIT I", "UNIT 1", "Module 1", "UNIT 1 - Differential Calculus", etc.
    const unitRegex = /^(?:UNIT|MODULE|CHAPTER)\s+[IVX0-9]+/i;

    for (let i = 0; i < lines.length; i++) {
      const line = lines[i].trim();
      if (!line) continue;

      if (unitRegex.test(line)) {
        if (currentUnit) {
          units.push(currentUnit);
        }
        currentUnit = { title: line, topics: "" };
      } else {
        if (currentUnit) {
          currentUnit.topics += (currentUnit.topics ? "\n" : "") + line;
        } else {
          // If topics appear before the first unit, we create a generic "UNIT I"
          currentUnit = { title: "UNIT I", topics: line };
        }
      }
    }
    
    if (currentUnit) {
      units.push(currentUnit);
    }

    if (units.length === 0) {
      setError("Could not detect any units. Please ensure it contains 'UNIT I', etc.");
    } else {
      setParsedUnits(units);
    }
  };

  const handleGeneratePDF = () => {
    if (parsedUnits.length === 0) return;

    const doc = new jsPDF();
    
    // Header
    doc.setFontSize(16);
    doc.setFont("helvetica", "bold");
    const finalSubjectName = localSubjectName.trim() || subjectName || "Subject";
    const title = `${finalSubjectName} - Syllabus`;
    doc.text(title, 14, 20);
    
    doc.setFontSize(10);
    doc.setFont("helvetica", "normal");
    doc.text("Generated by StudyMate", 14, 26);

    // Table data
    const tableBody = parsedUnits.map((u) => [u.title, u.topics]);

    autoTable(doc, {
      startY: 32,
      head: [["Unit", "Topics"]],
      body: tableBody,
      theme: "grid",
      headStyles: { fillColor: [44, 44, 42], textColor: [255, 255, 255], fontStyle: "bold" },
      columnStyles: {
        0: { cellWidth: 50, fontStyle: "bold" },
        1: { cellWidth: "auto" }
      },
      styles: {
        fontSize: 10,
        cellPadding: 4,
        overflow: "linebreak",
      },
    });

    // Download
    const fileName = `${finalSubjectName.replace(/[^a-zA-Z0-9_-]/g, '_')}_Syllabus.pdf`;
    doc.save(fileName);
  };

  return (
    <div className="fixed inset-0 z-[60] flex items-center justify-center bg-black/60 p-4 backdrop-blur-sm">
      <div className="flex max-h-[90vh] w-full max-w-2xl flex-col overflow-hidden rounded-lg border border-[#3A3A38] bg-[#1F1F1E] shadow-xl">
        {/* Header */}
        <div className="flex items-center justify-between border-b border-[#2E2E2C] px-5 py-4">
          <div className="flex items-center gap-2">
            <FileText className="h-5 w-5 text-[#8C8C8A]" />
            <h2 className="text-[15px] font-medium text-[#ECECEA]">Generate PDF from Text</h2>
          </div>
          <button onClick={onClose} className="text-[#8C8C8A] hover:text-[#ECECEA]">
            <X size={18} />
          </button>
        </div>

        {/* Content */}
        <div className="flex-1 overflow-y-auto p-5">
          {parsedUnits.length === 0 ? (
            <div className="flex flex-col gap-4">
              <div>
                <label className="mb-1 block text-[13px] font-medium text-[#ECECEA]">
                  Subject Name
                </label>
                <input
                  type="text"
                  value={localSubjectName}
                  onChange={(e) => setLocalSubjectName(e.target.value)}
                  placeholder="e.g. Data Structures"
                  className="w-full rounded-md border border-[#3A3A38] bg-[#2C2C2A] px-3 py-2 text-[13px] text-[#ECECEA] placeholder:text-[#5A5A58] focus:border-[#4A4A48] focus:outline-none"
                />
              </div>
              <div className="flex flex-col gap-2">
                <label className="text-[13px] font-medium text-[#ECECEA]">
                  Syllabus Content
                </label>
                <p className="text-[12px] text-[#8C8C8A]">
                  Paste your syllabus text below. Ensure units start with <b>UNIT I</b>, <b>MODULE 1</b>, or similar.
                </p>
                <textarea
                  value={text}
                  onChange={(e) => setText(e.target.value)}
                  placeholder={"UNIT I — DIFFERENTIAL CALCULUS\nRepresentation of functions - Limit of a function...\n\nUNIT II — FUNCTIONS OF SEVERAL VARIABLES\nPartial differentiation..."}
                  className="h-64 w-full resize-none rounded-md border border-[#3A3A38] bg-[#2C2C2A] p-3 text-[13px] text-[#ECECEA] placeholder:text-[#5A5A58] focus:border-[#4A4A48] focus:outline-none"
                />
                {error && <p className="text-[12px] text-red-400">{error}</p>}
              </div>
            </div>
          ) : (
            <div className="flex flex-col gap-4">
              <div className="flex items-center gap-2 rounded-md border border-green-500/30 bg-green-500/10 p-3 text-[13px] text-green-400">
                <CheckCircle2 size={16} />
                <span>Successfully parsed {parsedUnits.length} units!</span>
              </div>
              
              <div className="max-h-64 overflow-y-auto rounded-md border border-[#3A3A38] bg-[#2C2C2A]">
                {parsedUnits.map((u, i) => (
                  <div key={i} className={`p-3 ${i !== parsedUnits.length - 1 ? "border-b border-[#3A3A38]" : ""}`}>
                    <p className="mb-1 text-[13px] font-semibold text-[#ECECEA]">{u.title}</p>
                    <p className="whitespace-pre-wrap text-[12px] text-[#8C8C8A]">{u.topics}</p>
                  </div>
                ))}
              </div>
            </div>
          )}
        </div>

        {/* Footer */}
        <div className="flex items-center justify-end gap-3 border-t border-[#2E2E2C] px-5 py-4">
          <button
            onClick={() => {
              if (parsedUnits.length > 0) {
                setParsedUnits([]);
              } else {
                onClose();
              }
            }}
            className="rounded-md border border-[#3A3A38] px-4 py-2 text-[13px] text-[#B0B0AE] transition-colors hover:bg-[#2C2C2A]"
          >
            {parsedUnits.length > 0 ? "Edit Text" : "Cancel"}
          </button>
          
          {parsedUnits.length === 0 ? (
            <button
              onClick={handleParse}
              className="rounded-md border border-[#4A4A48] bg-[#2C2C2A] px-4 py-2 text-[13px] text-[#ECECEA] transition-colors hover:bg-[#333331]"
            >
              Preview PDF
            </button>
          ) : (
            <button
              onClick={handleGeneratePDF}
              className="rounded-md bg-[#ECECEA] px-4 py-2 text-[13px] font-medium text-[#1C1C1B] transition-colors hover:bg-white"
            >
              Download PDF
            </button>
          )}
        </div>
      </div>
    </div>
  );
}